BEGIN;

CREATE TABLE IF NOT EXISTS coordinator_deployment_batches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coordinator_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  batch_number integer NOT NULL CHECK (batch_number > 0),
  creation_key uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (coordinator_id, batch_number),
  UNIQUE (coordinator_id, creation_key)
);

ALTER TABLE deployment_requests ADD COLUMN IF NOT EXISTS coordinator_batch_id integer
  REFERENCES coordinator_deployment_batches(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_deployment_requests_coordinator_batch
  ON deployment_requests (coordinator_batch_id) WHERE coordinator_batch_id IS NOT NULL;

-- Keep existing published deployments live and include each in batch history.
WITH numbered AS (
  SELECT dr.id, dr.coordinator_id, COALESCE(tb.created_at, dr.created_at, now()) AS created_at,
    (COALESCE(existing.last_number, 0) + row_number() OVER (
      PARTITION BY dr.coordinator_id ORDER BY COALESCE(tb.created_at, dr.created_at), dr.id
    ))::integer AS batch_number
  FROM deployment_requests dr
  JOIN teacher_batches tb ON tb.id = dr.teacher_batch_id
  LEFT JOIN (
    SELECT coordinator_id, max(batch_number) AS last_number
    FROM coordinator_deployment_batches GROUP BY coordinator_id
  ) existing ON existing.coordinator_id = dr.coordinator_id
  WHERE dr.workflow_version = 2 AND dr.coordinator_batch_id IS NULL
), created AS (
  INSERT INTO coordinator_deployment_batches (coordinator_id, batch_number, created_at)
  SELECT coordinator_id, batch_number, created_at FROM numbered
  RETURNING id, coordinator_id, batch_number
)
UPDATE deployment_requests dr SET coordinator_batch_id = created.id
FROM numbered JOIN created USING (coordinator_id, batch_number)
WHERE dr.id = numbered.id;

COMMIT;

